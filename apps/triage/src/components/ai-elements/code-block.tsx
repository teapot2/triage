export const CodeBlockContent = ({
  code,
  language,
  showLineNumbers = false,
  wrap = false,
}: {
  code: string;
  language: BundledLanguage;
  showLineNumbers?: boolean;
  wrap?: boolean;
}) => {
  // Memoized raw tokens for immediate display
  const rawTokens = useMemo(() => createRawTokens(code), [code]);

  // The token cache is per process: warm on a server that has highlighted
  // this code before, empty in a fresh browser. So the server render and the
  // hydrating render both show raw tokens, and the cache is read only after
  // hydration (false from the server snapshot, true from the client's).
  // A block mounted later, e.g. on client navigation, reads it right away.
  const hydrated = useSyncExternalStore(
    subscribeNever,
    () => true,
    () => false
  );

  // Synchronous cache lookup — avoids setState in effect for cached results
  const syncTokens = useMemo(
    () => (hydrated ? (highlightCode(code, language) ?? rawTokens) : rawTokens),
    [hydrated, code, language, rawTokens]
  );

  // Async highlighting result (populated after shiki loads)
  const [asyncTokens, setAsyncTokens] = useState<TokenizedCode | null>(null);
  const asyncKeyRef = useRef({ code, language });

  // Invalidate stale async tokens synchronously during render
  if (
    asyncKeyRef.current.code !== code ||
    asyncKeyRef.current.language !== language
  ) {
    asyncKeyRef.current = { code, language };
    setAsyncTokens(null);
  }

  useEffect(() => {
    let cancelled = false;

    highlightCode(code, language, (result) => {
      if (!cancelled) {
        setAsyncTokens(result);
      }
    });

    return () => {
      cancelled = true;
    };
  }, [code, language]);

  const tokenized = asyncTokens ?? syncTokens;

  return (
    <div className="relative overflow-auto">
      <CodeBlockBody
        showLineNumbers={showLineNumbers}
        tokenized={tokenized}
        wrap={wrap}
      />
    </div>
  );
};

export const CodeBlock = ({
  code,
  language,
  showLineNumbers = false,
  className,
  children,
  ...props
}: CodeBlockProps) => {
  const [wrap, setWrap] = useState(false);
  const contextValue = useMemo(() => ({ code, wrap, setWrap }), [code, wrap]);

  return (
    <CodeBlockContext.Provider value={contextValue}>
      <CodeBlockContainer className={className} language={language} {...props}>
        {children}
        <CodeBlockContent
          code={code}
          language={language}
          showLineNumbers={showLineNumbers}
          wrap={wrap}
        />
      </CodeBlockContainer>
    </CodeBlockContext.Provider>
  );
};

// Toggles wrapping long lines, as ChatGPT's code blocks do. Off by default,
// so code keeps its layout until someone asks for it to fit. Its tooltip,
// like the copy button's, isn't hoverable: they sit side by side, and a
// hoverable one would stay open over its neighbour and block its tooltip.
export const CodeBlockWrapButton = ({
  className,
  ...props
}: ComponentProps<typeof Button>) => {
  const { wrap, setWrap } = useContext(CodeBlockContext);
  const label = wrap ? "Don't wrap lines" : "Wrap lines";

  return (
    <Tooltip disableHoverableContent>
      <TooltipTrigger asChild>
        <Button
          aria-label={label}
          aria-pressed={wrap}
          className={cn("shrink-0", wrap && "bg-muted text-foreground", className)}
          onClick={() => setWrap(!wrap)}
          size="icon"
          variant="ghost"
          {...props}
        >
          <WrapTextIcon size={14} />
        </Button>
      </TooltipTrigger>
      <TooltipContent>{label}</TooltipContent>
    </Tooltip>
  );
};

export type CodeBlockCopyButtonProps = ComponentProps<typeof Button> & {
  onCopy?: () => void;
  onError?: (error: Error) => void;
  timeout?: number;
};

export const CodeBlockCopyButton = ({
  onCopy,
  onError,
  timeout = 2000,
  children,
  className,
  ...props
}: CodeBlockCopyButtonProps) => {
  const [isCopied, setIsCopied] = useState(false);
  const timeoutRef = useRef<number>(0);
  const { code } = useContext(CodeBlockContext);

  const copyToClipboard = useCallback(async () => {
    if (typeof window === "undefined" || !navigator?.clipboard?.writeText) {
      onError?.(new Error("Clipboard API not available"));
      return;
    }

    try {
      if (!isCopied) {
        await navigator.clipboard.writeText(code);
        setIsCopied(true);
        onCopy?.();
        timeoutRef.current = window.setTimeout(
          () => setIsCopied(false),
          timeout
        );
      }
    } catch (error) {
      onError?.(error as Error);
    }
  }, [code, onCopy, onError, timeout, isCopied]);

  useEffect(
    () => () => {
      window.clearTimeout(timeoutRef.current);
    },
    []
  );

  const Icon = isCopied ? CheckIcon : CopyIcon;
  // Once a copy has happened, each icon swap scales in; on load the copy
  // icon just shows.
  const swapped = useChangedSinceMount(isCopied);

  return (
    <Tooltip disableHoverableContent>
      <TooltipTrigger asChild>
        <Button
          aria-label="Copy code"
          className={cn("shrink-0", className)}
          onClick={copyToClipboard}
          size="icon"
          variant="ghost"
          {...props}
        >
          {children ?? (
            <Icon
              className={cn(
                swapped &&
                  "animate-in fade-in-0 zoom-in-50 duration-150 ease-out motion-reduce:animate-none"
              )}
              size={14}
            />
          )}
        </Button>
      </TooltipTrigger>
      <TooltipContent>{isCopied ? "Copied" : "Copy code"}</TooltipContent>
    </Tooltip>
  );
};

