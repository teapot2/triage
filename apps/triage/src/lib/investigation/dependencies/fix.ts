// The fix stage for a dependency incident (fix/agent.ts hands over to this
// when the incident has a `dependency`): instead of a model writing a code
// patch, Triage raises the vulnerable package to the lowest release that
// fixes the advisory, and proves the bump by installing it in a sandbox and
// auditing again (sandbox.ts). No model is involved: the bump is
// deterministic, and the summary is written from the advisory.
//
// Two kinds of bump:
// - direct: the vulnerable copy is the service's own dependency (every chain
//   to it is just its name). Its range in the service's package.json is
//   raised, keeping the range's operator (^7.5.1 becomes ^7.5.2).
// - override: it comes in through other packages, so only the package
//   manager can move it. pnpm reads overrides from the workspace root's
//   pnpm-workspace.yaml and nowhere else: since pnpm 10 settings live
//   there, pnpm 12 no longer reads the "pnpm" field of any package.json at
//   all (it warns and ignores pnpm.overrides), and an app inside a
//   workspace never had a say. So the override goes into the workspace
//   root's pnpm-workspace.yaml, keyed on the vulnerable range
//   ("glob@>=9.0.0 <=14.0.1": "^14.0.2"), so the copies that were already
//   safe, and the other apps' unaffected ones, stay where they are. In the
//   fix's patch that file is named relative to the app
//   ("../../pnpm-workspace.yaml"); the PR applies it at the repository
//   root (fix/pull-request.ts). The sandbox is made its own workspace root
//   with a copy of that file, so the install there honours the override the
//   same way (sandbox.ts).
// The lockfile is left out of the patch: it is regenerated by the install
// (the PR regenerates it in its worktree when it can).

const execGit = promisify(execFile);

// --- versions ----------------------------------------------------------------
// The slice of semver an advisory's ranges use: comparators (>=, >, <=, <,
// =), caret and tilde ranges, x-ranges, partial versions and "||". Enough
// to pick a version from the registry's list, without a dependency on the
// semver package (which Triage doesn't otherwise need).

type Version = { major: number; minor: number; patch: number; pre: string[] };

export function parseVersion(v: string): Version | undefined {
  const m = /^\s*v?(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+[0-9A-Za-z.-]+)?\s*$/.exec(v);
  if (!m) return undefined;
  return { major: Number(m[1]), minor: Number(m[2]), patch: Number(m[3]), pre: m[4] ? m[4].split(".") : [] };
}

function comparePre(a: string[], b: string[]): number {
  // A release sorts after its prereleases.
  if (!a.length || !b.length) return b.length - a.length;
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] === undefined) return -1;
    if (b[i] === undefined) return 1;
    const [x, y] = [Number(a[i]), Number(b[i])];
    const numeric = Number.isInteger(x) && Number.isInteger(y);
    const c = numeric ? x - y : a[i].localeCompare(b[i]);
    if (c) return Math.sign(c);
  }
  return 0;
}

function compare(a: Version, b: Version): number {
  return Math.sign(a.major - b.major || a.minor - b.minor || a.patch - b.patch) || comparePre(a.pre, b.pre);
}

export function compareVersions(a: string, b: string): number {
  const [x, y] = [parseVersion(a), parseVersion(b)];
  if (!x || !y) return a.localeCompare(b);
  return compare(x, y);
}

type Comparator = { op: "<" | "<=" | ">" | ">=" | "="; v: Version };

const ver = (major: number, minor = 0, patch = 0): Version => ({ major, minor, patch, pre: [] });

// One space-separated comparator, as the comparators it stands for: a
// partial version or x-range is a span (1.2 is >=1.2.0 <1.3.0), a caret or
// tilde its usual span.
function comparators(token: string): Comparator[] | undefined {
  const m = /^(\^|~|>=|<=|>|<|=)?v?(\d+|[xX*])?(?:\.(\d+|[xX*]))?(?:\.(\d+|[xX*]))?(?:-([0-9A-Za-z.-]+))?(?:\+[0-9A-Za-z.-]+)?$/.exec(token);
  if (!m) return undefined;
  const op = m[1] ?? "";
  const part = (s: string | undefined) => (s === undefined || /^[xX*]$/.test(s) ? undefined : Number(s));
  const [major, minor, patch] = [part(m[2]), part(m[3]), part(m[4])];
  const pre = m[5] ? m[5].split(".") : [];
  if (major === undefined) return op === "<" || op === ">" ? [{ op: "<", v: ver(0) }] : [];
  const full = minor !== undefined && patch !== undefined;
  const v: Version = { major, minor: minor ?? 0, patch: patch ?? 0, pre };
  // The first version past a partial one: 1 → 2.0.0, 1.2 → 1.3.0.
  const next = minor === undefined ? ver(major + 1) : ver(major, minor + 1);
  if (op === "^") {
    const upper = major > 0 || minor === undefined ? ver(major + 1) : minor > 0 || patch === undefined ? ver(0, minor + 1) : ver(0, 0, v.patch + 1);
    return [{ op: ">=", v }, { op: "<", v: upper }];
  }
  if (op === "~") return [{ op: ">=", v }, { op: "<", v: minor === undefined ? ver(major + 1) : ver(major, minor + 1) }];
  if (full) return [{ op: (op || "=") as Comparator["op"], v }];
  // Partial versions with an operator: >1.2 is >=1.3.0, <=1.2 is <1.3.0.
  if (op === ">") return [{ op: ">=", v: next }];
  if (op === ">=") return [{ op: ">=", v }];
  if (op === "<") return [{ op: "<", v }];
  if (op === "<=") return [{ op: "<", v: next }];
  return [{ op: ">=", v }, { op: "<", v: next }];
}

// The range's alternatives, each a list of comparators that must all hold.
// Hyphen ranges ("1.2.3 - 2.3.4") become >= and <=.
function rangeSets(range: string): Comparator[][] | undefined {
  const sets: Comparator[][] = [];
  for (const alternative of range.split("||")) {
    const text = alternative
      .trim()
      .replace(/^(\S+)\s+-\s+(\S+)$/, ">=$1 <=$2")
      .replace(/(>=|<=|>|<|=|\^|~)\s+/g, "$1");
    const set: Comparator[] = [];
    for (const token of text.split(/\s+/).filter(Boolean)) {
      const c = comparators(token);
      if (!c) return undefined;
      set.push(...c);
    }
    sets.push(set);
  }
  return sets;
}

const holds = (v: Version, c: Comparator) => {
  const d = compare(v, c.v);
  return c.op === "<" ? d < 0 : c.op === "<=" ? d <= 0 : c.op === ">" ? d > 0 : c.op === ">=" ? d >= 0 : d === 0;
};

// Whether a release (never a prerelease: Triage doesn't propose one)
// satisfies the range. An unreadable range satisfies nothing.
export function satisfies(version: string, range: string): boolean {
  const v = parseVersion(version);
  const sets = rangeSets(range);
  if (!v || v.pre.length || !sets) return false;
  return sets.some((set) => set.every((c) => holds(v, c)));
}

const format = (v: Version) => `${v.major}.${v.minor}.${v.patch}`;

// Each alternative's lowest version, for when the registry can't be asked:
// ">=14.0.2" → 14.0.2, ">7.5.1" → 7.5.2, ">=1.2.0 <2 || >=2.1.0" → 1.2.0
// and 2.1.0. An alternative with no lower bound gives nothing.
export function lowerBounds(range: string): string[] {
  const out: string[] = [];
  for (const set of rangeSets(range) ?? []) {
    let low: Version | undefined;
    for (const c of set) {
      const v = c.op === ">" ? { ...c.v, patch: c.v.patch + 1, pre: [] } : c.op === ">=" || c.op === "=" ? c.v : undefined;
      if (v && (!low || compare(v, low) > 0)) low = v;
    }
    if (low && set.every((c) => holds(low!, c))) out.push(format(low));
  }
  return [...new Set(out)].sort(compareVersions);
}

// The version to move to: the lowest release that satisfies the patched
// range and isn't below the newest copy the tree holds now (so no copy is
// moved down, and a fix backported to the current major is preferred over
// a jump), else the lowest that satisfies it at all. `published` is the
// registry's list; without it, the range's own lower bounds stand in.
export function pickPatchedVersion(opts: { patched: string; current: string[]; published?: string[] }): string | undefined {
  const candidates = (opts.published ?? lowerBounds(opts.patched))
    .filter((v) => satisfies(v, opts.patched))
    .sort(compareVersions);
  const floor = opts.current.filter((v) => parseVersion(v)).sort(compareVersions).at(-1);
  return candidates.find((v) => !floor || compareVersions(v, floor) >= 0) ?? candidates[0];
}

// Whether moving from one version to another crosses a major version: the
// major changes, or, below 1.0.0 where a caret range stops at the minor,
// the minor does.
export function crossesMajor(from: string, to: string): boolean {
  const [a, b] = [parseVersion(from), parseVersion(to)];
  if (!a || !b) return false;
  return a.major !== b.major || (a.major === 0 && a.minor !== b.minor);
}

// --- the bump ------------------------------------------------------------------

type Manifest = Record<"dependencies" | "devDependencies" | "optionalDependencies", Record<string, string> | undefined>;
const sections = ["dependencies", "devDependencies", "optionalDependencies"] as const;

// The service's range raised to `to`, keeping its operator: ^7.5.1 →
// ^7.5.2, ~1.2.3 → ~1.3.0, 7.5.1 → 7.5.2; anything else (">=1", "*",
// "latest") becomes ^to.
export function raisedSpec(spec: string, to: string): string {
  const m = /^\s*([\^~]?)v?\d+(?:\.\d+){0,2}(?:-[0-9A-Za-z.-]+)?\s*$/.exec(spec);
  return m ? `${m[1]}${to}` : `^${to}`;
}

// package.json with one dependency's range changed, as text, so the rest
// of the file (order, indentation, line endings) stays byte for byte.
export function setDependencySpec(text: string, section: string, pkg: string, spec: string): string {
  const quote = (s: string) => JSON.stringify(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const start = new RegExp(`${quote(section)}\\s*:\\s*\\{`).exec(text);
  if (!start) throw new Error(`package.json has no ${section}`);
  const from = start.index + start[0].length;
  const entry = new RegExp(`(${quote(pkg)}\\s*:\\s*)"(?:[^"\\\\]|\\\\.)*"`).exec(text.slice(from));
  // The entry has to be inside the section, before its closing brace.
  const close = text.indexOf("}", from);
  if (!entry || from + entry.index > close) throw new Error(`${pkg} is not in package.json's ${section}`);
  const at = from + entry.index;
  return text.slice(0, at) + entry[1] + JSON.stringify(spec) + text.slice(at + entry[0].length);
}

const yamlKey = (line: string) => /^\s+(?:"((?:[^"\\]|\\.)*)"|'([^']*)'|([^:#][^:]*?))\s*:/.exec(line);

// pnpm-workspace.yaml with an entry in its top-level `overrides` map, as
// text: an entry with the same key is replaced, else one is added at the
// top of the map (made when there is none). Keys and values are written
// double-quoted, which YAML reads as plain strings.
export function setOverride(yaml: string, key: string, value: string): string {
  const eol = yaml.includes("\r\n") ? "\r\n" : "\n";
  const lines = yaml.split(/\r?\n/);
  const entry = `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`;
  const at = lines.findIndex((l) => /^overrides\s*:/.test(l));
  if (at === -1) {
    while (lines.length && lines.at(-1) === "") lines.pop();
    return [...lines, ...(lines.length ? [""] : []), "overrides:", entry, ""].join(eol);
  }
  // An empty inline map ("overrides: {}") becomes a block.
  if (/^overrides\s*:\s*\{\s*\}\s*$/.test(lines[at])) lines[at] = "overrides:";
  let end = at + 1;
  while (end < lines.length && (lines[end] === "" || /^\s/.test(lines[end]))) end++;
  for (let i = at + 1; i < end; i++) {
    const k = yamlKey(lines[i]);
    const name = k && (k[1] !== undefined ? JSON.parse(`"${k[1]}"`) : (k[2] ?? k[3]));
    if (name === key) {
      lines[i] = entry;
      return lines.join(eol);
    }
  }
  lines.splice(at + 1, 0, entry);
  return lines.join(eol);
}

export type Bump = NonNullable<Fix["bump"]>;

// One file the bump changes: `file` is relative to the app (the workspace
// root's pnpm-workspace.yaml is "../../pnpm-workspace.yaml" for an app two
// folders down); `target` says which file it is to the sandbox.
export type BumpChange = { file: string; target: "manifest" | "workspace"; before: string; after: string };

export type BumpPlan = { bump: Bump; changes: BumpChange[]; summary: string; risk: Fix["risk"]; overrideKey?: string };

// Whether the vulnerable copies are the service's own dependency: every
// chain to them is just the package's name, and package.json lists it.
export function isDirect(advisory: Pick<DependencyAdvisory, "package" | "paths">, manifest: Partial<Manifest>): boolean {
  const listed = sections.some((s) => manifest[s]?.[advisory.package] !== undefined);
  return listed && advisory.paths.length > 0 && advisory.paths.every((p) => p === advisory.package);
}

const highest = (versions: string[]) => [...versions].sort(compareVersions).at(-1) ?? versions[0];

// The bump for an advisory, as file changes. `workspace` is the
// pnpm-workspace.yaml that takes an override: its path relative to the app
// and its text now ("" when there is none yet).
export function planBump(
  advisory: Pick<DependencyAdvisory, "advisoryId" | "package" | "versions" | "vulnerable" | "paths" | "direct">,
  to: string,
  manifest: { text: string },
  workspace: { file: string; text: string },
): BumpPlan {
  const json = JSON.parse(manifest.text) as Partial<Manifest>;
  const from = highest(advisory.versions);
  const major = advisory.versions.some((v) => crossesMajor(v, to));
  const majorNote = major ? ` This crosses a major version (${from} to ${to}), so read the package's changelog for breaking changes.` : "";
  const risk: Fix["risk"] = major ? "medium" : "low";
  if (isDirect(advisory, json)) {
    const section = sections.find((s) => json[s]?.[advisory.package] !== undefined)!;
    const spec = json[section]![advisory.package];
    const raised = raisedSpec(spec, to);
    return {
      bump: { package: advisory.package, from, to, kind: "direct", major },
      changes: [{ file: "package.json", target: "manifest", before: manifest.text, after: setDependencySpec(manifest.text, section, advisory.package, raised) }],
      summary: `Raise ${advisory.package} from ${spec} to ${raised} in package.json, so the service installs ${to}, the lowest release that fixes ${advisory.advisoryId}.${majorNote}`,
      risk,
    };
  }
  // Keyed on the vulnerable range, so only the copies the advisory covers
  // move; a range pnpm couldn't read falls back to everything below `to`.
  const key = `${advisory.package}@${advisory.vulnerable && rangeSets(advisory.vulnerable) ? advisory.vulnerable : `<${to}`}`;
  const value = `^${to}`;
  const through = advisory.direct.filter((d) => d !== advisory.package);
  return {
    bump: { package: advisory.package, from, to, kind: "override", major },
    changes: [{ file: workspace.file, target: "workspace", before: workspace.text, after: setOverride(workspace.text, key, value) }],
    summary: `Override ${advisory.package} to ${value} in the workspace's pnpm-workspace.yaml (${JSON.stringify(key)}), since it only comes in through ${through.join(", ") || "other packages"}; ${to} is the lowest release that fixes ${advisory.advisoryId}.${majorNote}`,
    risk,
    overrideKey: key,
  };
}

// The fix's unified diff. A file outside the app ("../../pnpm-workspace.yaml")
// is diffed under its base name, since unifiedDiff stages files inside its
// own folder, and renamed in the diff's headers after.
export async function bumpPatch(name: string, changes: BumpChange[]): Promise<string> {
  const staged = changes.map((c) => ({ ...c, staged: c.file.startsWith("../") ? `.triage-outside/${path.posix.basename(c.file)}` : c.file }));
  let patch = await unifiedDiff(name, staged.map((c) => ({ file: c.staged, before: c.before, after: c.after })));
  for (const c of staged) {
    if (c.staged === c.file) continue;
    patch = patch.replaceAll(`--- a/${c.staged}`, `--- a/${c.file}`).replaceAll(`+++ b/${c.staged}`, `+++ b/${c.file}`);
  }
  return patch;
}

// The versions the registry has published for the package, oldest first,
// or undefined when it can't be asked (offline, a registry error). The name
// comes from the audit, but it reaches a shell on Windows, so anything that
// isn't a package name is refused.
export async function publishedVersions(pkg: string, cwd: string, run = runPackageManager): Promise<string[] | undefined> {
  if (!/^(@[a-z0-9][\w.-]*\/)?[a-z0-9][\w.-]*$/i.test(pkg)) return undefined;
  const out = await run("pnpm", ["view", pkg, "versions", "--json"], cwd, 30_000);
  if (out.exitCode !== 0 || out.timedOut) return undefined;
  try {
    const json = JSON.parse(out.stdout.slice(out.stdout.search(/[[{"]/))) as unknown;
    const list = Array.isArray(json) ? json : typeof json === "string" ? [json] : undefined;
    return list?.filter((v): v is string => typeof v === "string");
  } catch {
    return undefined;
  }
}

// --- the PR's base ---------------------------------------------------------------

export type DeployedRelease = { sha: string; branch?: string };

// The release branch a dependency fix's PR goes against: the deployed
// release's, when that release's commit is what brought the package in (its
// changes to the service's package.json or the lockfile name it). main
// doesn't have the package then, so a bump against it couldn't apply.
// Undefined otherwise, for the default branch. `release` defaults to the one
// Shopfront's ops API says is deployed now.
export async function dependencyPrBase(
  incident: Pick<Incident, "dependency">,
  appDir: string,
  release: () => Promise<DeployedRelease | undefined> = fetchRelease,
): Promise<string | undefined> {
  const pkg = incident.dependency?.package;
  if (!pkg) return undefined;
  const deployed = await release().catch(() => undefined);
  if (!deployed?.branch || !/^[0-9a-f]{7,40}$/i.test(deployed.sha)) return undefined;
  return (await releaseBringsIn(appDir, deployed.sha, pkg)) ? deployed.branch : undefined;
}

// Whether the commit's changes to the app's package.json or the workspace
// lockfile add a line naming the package.
export async function releaseBringsIn(appDir: string, sha: string, pkg: string): Promise<boolean> {
  try {
    const git = async (args: string[]) => (await execGit("git", ["-C", appDir, ...args], { windowsHide: true, maxBuffer: 1 << 26 })).stdout;
    const root = (await git(["rev-parse", "--show-toplevel"])).trim();
    const lock = await findLockfile(appDir);
    const files = [path.join(/* turbopackIgnore: true */ appDir, "package.json"), ...(lock ? [path.join(/* turbopackIgnore: true */ lock.root, "pnpm-lock.yaml"), path.join(/* turbopackIgnore: true */ lock.root, "package-lock.json")] : [])].map(
      (f) => path.relative(root, f).split(path.sep).join("/"),
    );
    const diff = await git(["-C", root, "show", "--format=", "--no-color", sha, "--", ...files]);
    const name = pkg.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const mentions = new RegExp(`(^|[\\s"'/])${name}(@|["':\\s]|$)`);
    return diff.split("\n").some((l) => l.startsWith("+") && !l.startsWith("+++") && mentions.test(l.slice(1)));
  } catch {
    return false;
  }
}

// --- the stage ---------------------------------------------------------------------

export type DependencyFixOptions = {
  notify?: boolean;
  // Tests: the registry's versions instead of asking it, and the sandbox's
  // commands stubbed.
  published?: (pkg: string, cwd: string) => Promise<string[] | undefined>;
  runner?: Runner;
  database?: Parameters<typeof proveBump>[0]["database"];
};

// Writes and proves the bump for the incident's advisory, recording the
// outcome on the incident as the fix stage does: proven (awaiting
// approval), declined (no release fixes it), or failed (the proof or the
// setup failed). Never throws.
export async function runDependencyFix(recorder: InvestigationRecorder, appDir: string, opts: DependencyFixOptions = {}) {
  const advisory = recorder.incident.dependency!;
  let fixRun: FixRun = { status: "writing", attempt: 0, startedAt: new Date().toISOString() };
  const setFixRun = (patch: Partial<FixRun>) => {
    fixRun = { ...fixRun, ...patch };
    recorder.update({ fixRun });
  };
  setFixRun({});
  const end = (patch: Partial<FixRun>, extra: Partial<Pick<Incident, "validation">> = {}) => {
    fixRun = { ...fixRun, ...patch, finishedAt: new Date().toISOString() };
    recorder.update({ fixRun, ...extra });
  };

  try {
    if (!advisory.patched) {
      return end({
        status: "declined",
        declinedBecause: `No patched version of ${advisory.package} is published for ${advisory.advisoryId} (vulnerable: ${advisory.vulnerable || "every version"}), so there is nothing to bump to yet.`,
      });
    }
    const lock = await findLockfile(appDir);
    if (lock?.packageManager !== "pnpm") {
      return end({ status: "failed", error: `Triage writes dependency bumps for pnpm projects; ${appDir} has ${lock ? "an npm lockfile" : "no lockfile"}.` });
    }
    const published = await (opts.published ?? publishedVersions)(advisory.package, lock.root);
    const to = pickPatchedVersion({ patched: advisory.patched, current: advisory.versions, published });
    if (!to) {
      return end({
        status: "declined",
        declinedBecause: `No published version of ${advisory.package} satisfies the advisory's patched range (${advisory.patched}).`,
      });
    }

    const manifestText = await readFile(path.join(/* turbopackIgnore: true */ appDir, "package.json"), "utf8");
    const workspacePath = path.join(/* turbopackIgnore: true */ lock.root, "pnpm-workspace.yaml");
    const workspaceText = await readFile(workspacePath, "utf8").catch(() => "");
    const workspaceFile = path.relative(appDir, workspacePath).split(path.sep).join("/");
    const plan = planBump(advisory, to, { text: manifestText }, { file: workspaceFile, text: workspaceText });

    setFixRun({ status: "testing", attempt: 1 });
    const proof: BumpProof = await proveBump({
      appDir,
      name: `${recorder.incident.id}-deps`,
      service: recorder.incident.service,
      advisoryId: advisory.advisoryId,
      lockRoot: lock.root,
      importer: importerOf(lock.root, appDir),
      changes: plan.changes,
      runner: opts.runner,
      database: opts.database,
    });
    if (!proof.ok) {
      return end({ status: "failed", error: proof.problems[0].split("\n")[0], rejections: proof.problems.map((p) => p.split("\n")[0]) }, {
        validation: proof.runs.length ? proof.runs : undefined,
      });
    }

    const fix: Fix = {
      summary: plan.summary + (proof.offline ? " The sandbox couldn't reach the registry to install it, so only the lockfile was resolved and re-audited; typecheck and tests didn't run." : ""),
      patch: await bumpPatch(recorder.incident.id, plan.changes),
      files: plan.changes.map((c) => c.file),
      // The fix's "regression test" is the re-audit: it lists the advisory
      // before the bump and not after (sandbox.ts records both runs).
      regressionTest: { file: plan.changes[0].file, name: reauditTestName(advisory.advisoryId) },
      risk: plan.risk,
      touchesData: false,
      // A package.json or pnpm-workspace.yaml change has no data side.
      dataChange: { detected: false, reasons: [], files: [], unproven: [] },
      bump: plan.bump,
    };
    fixRun = { ...fixRun, status: "proven", finishedAt: new Date().toISOString(), error: undefined };
    recorder.update({
      fix,
      validation: proof.runs,
      fixRun,
      status: "awaiting_approval",
      approval: { state: "pending", requestedAt: new Date().toISOString() },
    });
    if (opts.notify !== false) void recorder.flush().then(() => notify("fix_ready", recorder.incident));
  } catch (err) {
    console.error("[triage] dependency fix failed", recorder.incident.id, err);
    end({ status: "failed", error: errorMessage(err).split("\n")[0] });
  }
}
